#Objetivo: Ler um número inteiro e informar se ele negativo ou positivo.

#Entrada: Solicita um número ao usuário
numero = int(input("Digite um número positivo ou negativo: "))

#Decisão 1: Verifica se o número é positivo
if numero >= 0:
    #Saída 1: exibe a mensagem informando que o número é positivo
    print("Positivo")
#Decisão
else:
    #Saída 2: exibe a mensagem informando que o número é negativo
    print("Negativo")    