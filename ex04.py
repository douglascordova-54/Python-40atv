#Exemplo04- Transformando Celsius em Fahrenheit
#Aluno: Douglas William de Lima Cordova
#Objetivo: Ler uma temperatura em °C e exibir ela em °F

#Entrada: Solicita a temperatura em °C ao usuário
celsius = float(input("Digite a temperatura em °C: "))

#Processamento: Faz a conversão para °F
fahrenheit = (celsius * 1.8 + 32)

#Saída: Exibe a temperatura em °F ao usuário
print("Temperatura em Fahrenheit: ", fahrenheit)
