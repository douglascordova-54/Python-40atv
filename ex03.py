#Exemplo03-Média de três notas
#Aluno: Douglas William de Lima Cordova
#Objetivo: Ler três notas e exibir a média aritmética

#Entrada: Solicita as notas ao usuário
nota1 = float(input("Digite a 1° nota: "))
nota2 = float(input("Digite a 2° nota: "))
nota3 = float(input("Digite a 3° nota: "))

#Processamento calcula a média das três notas
media  = (nota1 + nota2 + nota3) / 3

#Saída: Mostra a média das três notas ao usuário
print("Média: ", media)
